<?php

	namespace Quellabs\Canvas\Security\Policies;

	use Quellabs\Canvas\Security\SecurityHeaderPolicyInterface;
	use Quellabs\Contracts\Configuration\ConfigProviderInterface;
	use Symfony\Component\HttpFoundation\Request;
	use Symfony\Component\HttpFoundation\Response;

	/**
	 * Opt-in CORS policy. Add this class to config/app.php's security_header_policy
	 * (alongside a header policy such as BasicSecurityHeaderPolicy, since this policy
	 * does not itself add any of the Basic/Medium/Strict headers) or to a route's
	 * SecurityHeadersAspect override, to grant cross-origin access to the exact origins
	 * listed in config/cors.php. Absent configuration, or the defaults generated by
	 * cors:init, grant no cross-origin access.
	 *
	 * Only exact http(s) origins are accepted; wildcard '*' and the opaque 'null'
	 * origin are rejected, both in configuration and at request time. This policy
	 * never authenticates or authorizes a request; it only decides whether to add
	 * the headers a browser needs to permit a cross-origin response.
	 */
	class CorsSecurityHeaderPolicy implements SecurityHeaderPolicyInterface {

		/** @var array{scheme: string, host: string, port: int}[] Parsed, exact allowed origins */
		private array $allowedOrigins;

		/** @var string[] Methods allowed cross-origin, as configured */
		private array $allowedMethods;

		/** @var string[] Request headers allowed cross-origin, as configured */
		private array $allowedHeaders;

		/** @var string[] Response headers exposed to cross-origin scripts, as configured */
		private array $exposedHeaders;

		/** @var bool Whether Access-Control-Allow-Credentials: true is sent for allowed origins */
		private bool $allowCredentials;

		/** @var int Access-Control-Max-Age in seconds; 0 omits the header */
		private int $maxAge;

		/**
		 * Constructor
		 * @param ConfigProviderInterface $configProvider Loads config/cors.php (and its .local.php override); absent file defaults to deny-all
		 */
		public function __construct(ConfigProviderInterface $configProvider) {
			$config = $configProvider->loadConfigFile('cors.php');

			$this->allowedOrigins = $this->parseAllowedOrigins($config->get('allowed_origins', []));
			$this->allowedMethods = $this->validateStringList($config->get('allowed_methods', []), 'allowed_methods');
			$this->allowedHeaders = $this->validateStringList($config->get('allowed_headers', []), 'allowed_headers');
			$this->exposedHeaders = $this->validateStringList($config->get('exposed_headers', []), 'exposed_headers');
			$this->allowCredentials = (bool)$config->get('allow_credentials', false);
			$this->maxAge = (int)$config->get('max_age', 0);
		}

		/**
		 * Applies CORS headers to the response, in place
		 * @param Request $request The request, inspected for Origin and, for preflights, Access-Control-Request-*
		 * @param Response $response The response to modify
		 * @return void
		 */
		public function apply(Request $request, Response $response): void {
			$origin = $request->headers->get('Origin');

			if ($origin === null || $origin === '') {
				return;
			}

			if ($request->isMethod('OPTIONS') && $request->headers->has('Access-Control-Request-Method')) {
				$this->applyPreflight($request, $response, $origin);
			} else {
				$this->applyActual($response, $origin);
			}
		}

		/**
		 * Applies CORS headers to an ordinary (non-preflight) request
		 * @param Response $response The response to modify
		 * @param string $origin The request's Origin header value
		 * @return void
		 */
		private function applyActual(Response $response, string $origin): void {
			$this->mergeVary($response, ['Origin']);

			// A pre-existing Access-Control-Allow-Origin means the controller or an
			// earlier policy already made the CORS decision for this response; that
			// choice is route-owned and must not be replaced or second-guessed here.
			if ($response->headers->has('Access-Control-Allow-Origin')) {
				return;
			}

			if (!$this->isOriginAllowed($origin)) {
				return;
			}

			$response->headers->set('Access-Control-Allow-Origin', $origin);
			$this->setCredentialsHeaderIfConfigured($response);
			$this->setExposeHeadersIfConfigured($response);
		}

		/**
		 * Applies CORS headers to a preflight request (OPTIONS with Access-Control-Request-Method)
		 * @param Request $request The preflight request
		 * @param Response $response The response to modify; carries the route's matched Allow header
		 * @param string $origin The request's Origin header value
		 * @return void
		 */
		private function applyPreflight(Request $request, Response $response, string $origin): void {
			$this->mergeVary($response, ['Origin', 'Access-Control-Request-Method', 'Access-Control-Request-Headers']);

			if ($response->headers->has('Access-Control-Allow-Origin')) {
				return;
			}

			$requestedMethod = (string)$request->headers->get('Access-Control-Request-Method');
			$routeAllowedMethods = $this->parseCommaSeparated($response->headers->get('Allow'));
			$requestedHeaders = $this->parseCommaSeparated($request->headers->get('Access-Control-Request-Headers'));

			if (
				!$this->isOriginAllowed($origin)
				|| $routeAllowedMethods === []
				|| !in_array($requestedMethod, $routeAllowedMethods, true)
				|| !in_array($requestedMethod, $this->allowedMethods, true)
				|| !$this->allRequestedHeadersAllowed($requestedHeaders)
			) {
				return;
			}

			$response->headers->set('Access-Control-Allow-Origin', $origin);
			$this->setCredentialsHeaderIfConfigured($response);

			// The full intersection/list, not just what was requested: the browser
			// caches this preflight result and may reuse it for another permitted
			// method/header combination on the same URL.
			$allowedMethodsForRoute = array_values(array_intersect($this->allowedMethods, $routeAllowedMethods));
			$response->headers->set('Access-Control-Allow-Methods', implode(', ', $allowedMethodsForRoute));
			$response->headers->set('Access-Control-Allow-Headers', implode(', ', $this->allowedHeaders));

			if ($this->maxAge > 0) {
				$response->headers->set('Access-Control-Max-Age', (string)$this->maxAge);
			}
		}

		/**
		 * Sets Access-Control-Allow-Credentials when configured, unless already present
		 * @param Response $response
		 * @return void
		 */
		private function setCredentialsHeaderIfConfigured(Response $response): void {
			if ($this->allowCredentials && !$response->headers->has('Access-Control-Allow-Credentials')) {
				$response->headers->set('Access-Control-Allow-Credentials', 'true');
			}
		}

		/**
		 * Sets Access-Control-Expose-Headers when configured, unless already present
		 * @param Response $response
		 * @return void
		 */
		private function setExposeHeadersIfConfigured(Response $response): void {
			if ($this->exposedHeaders !== [] && !$response->headers->has('Access-Control-Expose-Headers')) {
				$response->headers->set('Access-Control-Expose-Headers', implode(', ', $this->exposedHeaders));
			}
		}

		/**
		 * Checks whether every requested header is in the configured allowlist, case-insensitively
		 * @param string[] $requestedHeaders Header names from Access-Control-Request-Headers
		 * @return bool
		 */
		private function allRequestedHeadersAllowed(array $requestedHeaders): bool {
			$allowedLower = array_map('strtolower', $this->allowedHeaders);

			foreach ($requestedHeaders as $header) {
				if (!in_array(strtolower($header), $allowedLower, true)) {
					return false;
				}
			}

			return true;
		}

		/**
		 * Checks whether the given Origin header value matches a configured allowed origin exactly
		 * @param string $origin Raw Origin header value
		 * @return bool
		 */
		private function isOriginAllowed(string $origin): bool {
			$parsed = $this->parseOrigin($origin);

			if ($parsed === null) {
				return false;
			}

			foreach ($this->allowedOrigins as $allowed) {
				if ($allowed === $parsed) {
					return true;
				}
			}

			return false;
		}

		/**
		 * Splits a comma-separated header value into trimmed, non-empty tokens
		 * @param string|null $value Raw header value
		 * @return string[]
		 */
		private function parseCommaSeparated(?string $value): array {
			if ($value === null || trim($value) === '') {
				return [];
			}

			return array_values(array_filter(array_map('trim', explode(',', $value)), fn(string $token) => $token !== ''));
		}

		/**
		 * Merges header names into the response's Vary header without duplicating existing
		 * entries (case-insensitively), so repeated application stays idempotent
		 * @param Response $response
		 * @param string[] $names Header names to merge in
		 * @return void
		 */
		private function mergeVary(Response $response, array $names): void {
			$current = $response->getVary();
			$currentLower = array_map('strtolower', $current);

			foreach ($names as $name) {
				if (!in_array(strtolower($name), $currentLower, true)) {
					$current[] = $name;
					$currentLower[] = strtolower($name);
				}
			}

			// A single comma-joined line, not setVary()'s one-header-per-value array
			// form: keeps the merge a plain string replace, so it stays idempotent
			// regardless of how an earlier Vary value was itself represented.
			$response->headers->set('Vary', implode(', ', $current));
		}

		/**
		 * Validates and normalizes config/cors.php's 'allowed_origins' into parsed origin tuples
		 * @param mixed $origins Raw config value
		 * @return array{scheme: string, host: string, port: int}[]
		 */
		private function parseAllowedOrigins(mixed $origins): array {
			$list = $this->validateStringList($origins, 'allowed_origins');
			$parsed = [];

			foreach ($list as $origin) {
				$tuple = $this->parseOrigin($origin);

				if ($tuple === null) {
					throw new \RuntimeException(sprintf(
						"config/cors.php's 'allowed_origins' entry '%s' is invalid; only exact http(s) origins are accepted ('*' and 'null' are not supported).",
						$origin
					));
				}

				$parsed[] = $tuple;
			}

			return $parsed;
		}

		/**
		 * Parses an origin string into its scheme, host, and effective port, or null if it
		 * is not an exact http(s) origin (this rejects '*', 'null', and anything with a path,
		 * query, fragment, or credentials)
		 * @param string $origin
		 * @return array{scheme: string, host: string, port: int}|null
		 */
		private function parseOrigin(string $origin): ?array {
			$trimmed = trim($origin);

			if ($trimmed === '' || $trimmed === '*' || strcasecmp($trimmed, 'null') === 0) {
				return null;
			}

			$parts = parse_url($trimmed);

			if ($parts === false || !isset($parts['scheme'], $parts['host'])) {
				return null;
			}

			if (isset($parts['path']) || isset($parts['query']) || isset($parts['fragment']) || isset($parts['user']) || isset($parts['pass'])) {
				return null;
			}

			$scheme = strtolower($parts['scheme']);

			if (!in_array($scheme, ['http', 'https'], true)) {
				return null;
			}

			$port = $parts['port'] ?? ($scheme === 'https' ? 443 : 80);

			return ['scheme' => $scheme, 'host' => strtolower($parts['host']), 'port' => $port];
		}

		/**
		 * Validates a config/cors.php list value as an array of non-empty strings
		 * @param mixed $value Raw config value
		 * @param string $key Config key name, used in the error message
		 * @return string[]
		 */
		private function validateStringList(mixed $value, string $key): array {
			if (!is_array($value)) {
				throw new \RuntimeException(sprintf("config/cors.php's '%s' must be an array.", $key));
			}

			foreach ($value as $entry) {
				if (!is_string($entry) || trim($entry) === '') {
					throw new \RuntimeException(sprintf("config/cors.php's '%s' entries must be non-empty strings.", $key));
				}
			}

			return array_values($value);
		}
	}
